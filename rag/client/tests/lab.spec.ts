test('a delayed preview does not override user navigation', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'Разбиение и индексы' }).click()
  await page.route('**/api/v1/preview', async route => {
    await new Promise(resolve => setTimeout(resolve, 400))
    await route.continue()
  })
  const previewRequest = page.waitForRequest(request => request.url().endsWith('/api/v1/preview'))
  const previewResponse = page.waitForResponse(response => response.url().endsWith('/api/v1/preview'))
  await page.getByRole('button', { name: 'Посмотреть чанки' }).click()
  await previewRequest
  await page.getByRole('button', { name: 'Диагностический поиск' }).click()
  await previewResponse
  await expect(page.getByRole('button', { name: 'Найти в книге' })).toBeEnabled()
  await expect(page.getByRole('heading', { name: 'Найдите фрагменты книги' })).toBeVisible()
})
