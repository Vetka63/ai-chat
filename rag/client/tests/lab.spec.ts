test('ready indices compare export and real search through UI', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'Сравнение стратегий' }).click()
  await page.locator('.index-option').filter({ hasText: 'Фиксированный размер' }).first().getByRole('checkbox').check()
  await page.locator('.index-option').filter({ hasText: 'По структуре' }).first().getByRole('checkbox').check()
  await page.getByRole('button', { name: 'Сравнить индексы' }).click()
  await expect(page.getByText('Одинаковый корпус и embedding space — сравнение допустимо.')).toBeVisible()
  const downloadPromise = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Скачать Markdown' }).click()
  const download = await downloadPromise
  expect(download.suggestedFilename()).toMatch(/\.md$/)
  await page.getByRole('button', { name: 'Диагностический поиск' }).click()
  await page.locator('.search-indexes label').filter({ hasText: 'Фиксированный размер' }).first().getByRole('checkbox').check()
  await page.locator('.search-indexes label').filter({ hasText: 'По структуре' }).first().getByRole('checkbox').check()
  await page.getByRole('textbox', { name: 'Ваш поисковый вопрос' }).fill('Чем отличаются reset --soft, --mixed и --hard?')
  await page.getByRole('button', { name: 'Найти в книге' }).click()
  await expect(page.locator('.search-columns > div')).toHaveCount(2, { timeout: 60_000 })
  await expect(page.locator('.search-hit')).toHaveCount(10)
  await page.evaluate(() => window.scrollTo(0, 0))
  await page.screenshot({ path: 'test-results/day21-search-desktop.png', fullPage: false })
  await page.getByRole('button', { name: 'Открыть сохранённый источник' }).first().click()
  await expect(page.getByRole('dialog')).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(page.getByRole('dialog')).toHaveCount(0)
})

